export function main(): void {
  let args: CliArgs
  try {
    args = parseArgs(process.argv.slice(2))
  } catch (err) {
    if (err instanceof ScaffoldError) {
      console.error(`scaffold-platform: ${err.message}`)
      process.exitCode = 1
      return
    }
    throw err
  }

  const {key, displayName, write} = args
  const stub = strategyStub(key, displayName)
  const snippets = wiringSnippets(key, displayName)

  const scaffoldDir = path.join(REPO_ROOT, "src", "lib", "parsers", "scaffold")
  const stubPath = path.join(scaffoldDir, `${key}-platform.scaffold.ts`)
  const relStubPath = path.relative(REPO_ROOT, stubPath)

  if (!write) {
    console.log(
      `# DRY RUN (no files written). Re-run with --write to create ${relStubPath}\n`,
    )
    console.log(`----- ${relStubPath} -----`)
    console.log(stub)
    console.log(snippets)
    return
  }

  if (fs.existsSync(stubPath)) {
    console.error(
      `scaffold-platform: refusing to overwrite existing ${relStubPath}. ` +
        `Delete it first or pick a different key.`,
    )
    process.exitCode = 1
    return
  }

  fs.mkdirSync(scaffoldDir, {recursive: true})
  fs.writeFileSync(stubPath, stub, "utf-8")
  console.log(`scaffold-platform: wrote ${relStubPath}`)
  console.log(snippets)
}

// Run main() only when invoked as a script (tsx tools/scaffold-platform.ts
// / npm run scaffold:platform). Importing this module (the smoke test does)
// must NOT trigger generation — keeps the test in-process and instant.
const invokedPath = process.argv[1]
  ? path.resolve(process.argv[1])
  : ""
if (invokedPath === fileURLToPath(import.meta.url)) {
  main()
}
