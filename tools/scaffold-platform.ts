import * as fs from "node:fs"
import * as path from "node:path"
import {fileURLToPath} from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, "..")

export interface CliArgs {
  key: string
  displayName: string
  write: boolean
}

/** A platform key must be a safe lowercase identifier (used in a filename
 *  + as a TS class-name stem + as a registry map key). Reject anything
 *  that would not round-trip cleanly so a typo never produces broken code. */
export const KEY_RE = /^[a-z][a-z0-9-]{1,40}$/

export class ScaffoldError extends Error {}

export function parseArgs(argv: string[]): CliArgs {
  const positional: string[] = []
  let displayName = ""
  let write = false

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === "--write") {
      write = true
    } else if (arg === "--name") {
      const next = argv[i + 1]
      if (next === undefined) {
        throw new ScaffoldError('--name requires a value, e.g. --name "Acme Store"')
      }
      displayName = next
      i++
    } else if (arg.startsWith("--name=")) {
      displayName = arg.slice("--name=".length)
    } else if (arg.startsWith("--")) {
      throw new ScaffoldError(`Unknown flag: ${arg}`)
    } else {
      positional.push(arg)
    }
  }

  const key = positional[0]
  if (!key) {
    throw new ScaffoldError(
      'Usage: tsx tools/scaffold-platform.ts <key> [--name "Display Name"] [--write]',
    )
  }
  if (!KEY_RE.test(key)) {
    throw new ScaffoldError(
      `Invalid platform key "${key}". Expected lowercase letters/digits/'-' ` +
        `starting with a letter (matches the existing DETAIL_REGISTRY keys, ` +
        `e.g. "blankroom"; a digit-leading site like "8division" needs a ` +
        `letter-leading key such as "eightdivision").`,
    )
  }
  return {key, displayName: displayName || key, write}
}

/** lower-kebab/`-`/digits key -> UpperCamel class stem. */
export function toClassStem(key: string): string {
  return key
    .split("-")
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("")
}

