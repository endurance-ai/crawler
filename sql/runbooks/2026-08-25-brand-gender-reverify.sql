--
-- 원인은 셋이고 전부 "unisex 를 모름의 대체값으로 쓴" 같은 계열이다.
-- 검색 RPC 가 `p.gender && ARRAY[p_gender,'unisex']` 로 매칭하므로 unisex 는
-- 남녀 양쪽에 노출된다.
--
--   ① Taille — `platforms.ts` 의 `defaultGender: ["women"]` 가 사이트 전역이었다.
--      taille.kr 은 /Menshop 과 /Womenshop 을 모두 운영한다. MEN 부서 414행이
--      통째로 ["women"] 으로 적재돼 있었다.
--      → 설정을 메뉴별 성별 맵으로 교체(2026-08-25 라이브 브레드크럼 확인) +
--        imweb 엔진이 `category.categories[].url/gender` 를 소비하도록 수정.
--
--   ② etcseoul — 10개 카테고리를 전부 `gender: ["unisex"]` 로 적어 뒀다.
--      etcseoul.com 내비에는 성별 부서가 아예 없다. 게다가
--      resolveProductGenderWithSource 가 engine 근거를 무조건 최우선으로
--      반환해, 상품명에 `MEN'S` 가 박힌 상품도 텍스트 추론까지 내려가지 못했다.
--      → 카테고리 gender 제거 + 엔진 unisex 는 URL/텍스트의 구체 성별에
--        양보하도록 수정 (전 코퍼스에서 이 규칙이 뒤집는 행: 10개 플랫폼 267행).
--
--   ③ TONYWACK / Fabrégat — 상품 단위 근거가 DB 텍스트에 없어 브랜드 공식
--      카탈로그를 대조했다.
--      · TONYWACK: 자사몰 tonywack.com 이 여성 라인에만 `(W)` 접두어를 쓴다
--        (323번 카테고리 157개 전부 (W), 남성 606개 전부 없음). 전체 763개를
--        긁어 etcseoul 536행과 정규화 이름 대조.
--      · Fabrégat: 무신사 공식 입점의 `goodsNmEng` + `sex` 를 대조.
--        브랜드 전체는 공용 134 / 남성 94 라 사이트 기본값을 쓸 수 없다.
--        **확정 남성만** 교정하고 나머지는 손대지 않는다.
--
-- 손대지 않은 것:
--   · Uniqlo `PEACE FOR ALL Graphic T-Shirt | Hideki Kuriyama` (id 467198) —
--     Uniqlo US API 가 `genderName: "UNISEX"` 를 그대로 준다. 우리 값이 원본과
--     일치한다. 단 `sizeGender: "MEN"` 이라 여성에게 남성복으로 보인다 —
--     크롤러가 아니라 검색 노출 정책 문제다.
--   · Fabrégat `Pig-Dyeing Rolling Crop Short Sleeve T-shirt` — 무신사 공식
--     성별이 **공용**이다. 우리 값이 맞다.
--   · etcseoul 잔여 5,504행 — 상품명에도 URL 에도 성별 신호가 없다.
--     `["unisex"]` 인 채 `unverified_legacy` 로 남아 있다. 근거가 생기기 전에
--     건드리지 않는다.
--   · `블리치아트_ PinkFloyd Invisible Man T-Shirt [WHITE]` (id 478234) —
--     분류기가 `\bman\b` 로 men 을 뽑았으나 "Invisible Man" 은 고유명사다.
--     매니페스트에서 제외했다. product-gender.ts 어휘 규율의 알려진 약점.
--
-- 이 런북은 **UPDATE 만** 한다. products 삭제는 product_embeddings /
-- product_features / product_reviews 로 CASCADE 되므로 여기서 하지 않는다.
--
